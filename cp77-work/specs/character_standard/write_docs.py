def jt(layer, filt=None):
    rows = ['| joint | parent | rest position (m, x y z) | note |', '|---|---|---|---|']
    for j in J:
        if j['layer'] != layer: continue
        if j['name'].endswith('_r'): continue          # right side mirrors left (x negated); listed once
        if filt and not filt(j): continue
        p = ' '.join(f'{v:+.3f}' for v in j['rest_position_m'])
        rows.append(f"| `{j['name']}` | `{j['parent']}` | {p} | {j['note']} |")
    return '\n'.join(rows)

