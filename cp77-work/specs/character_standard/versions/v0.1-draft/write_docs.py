def regs(prefix_side=None):
    rows = ['| bit | region | bounded by | note |', '|---|---|---|---|']
    for r in R:
        if r['name'].endswith('_r'): continue
        rows.append(f"| {r['bit']} | `{r['name']}` | {', '.join(r['bounded_by'])} | {r['note']} |")
    return '\n'.join(rows)
